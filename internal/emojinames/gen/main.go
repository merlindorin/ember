// Command gen writes the shortcode table of package emojinames from
// GitHub's gemoji database (MIT): every alias, its emoji, and whether it
// takes a skin tone.
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"io"
	"log"
	"net/http"
	"os"
	"sort"
	"strconv"
	"strings"
)

func main() {
	src := flag.String("src", "", "gemoji's db/emoji.json, a URL or a file")
	out := flag.String("out", "names_gen.go", "the Go file to write")
	flag.Parse()
	data, err := read(*src)
	if err != nil {
		log.Fatal(err)
	}
	var db []struct {
		Emoji     string   `json:"emoji"`
		Aliases   []string `json:"aliases"`
		SkinTones bool     `json:"skin_tones"`
	}
	if err = json.Unmarshal(data, &db); err != nil {
		log.Fatal(err)
	}
	type row struct {
		name, emoji string
		tones       bool
	}
	var rows []row
	for _, e := range db {
		for _, a := range e.Aliases {
			rows = append(rows, row{a, e.Emoji, e.SkinTones})
		}
	}
	sort.Slice(rows, func(i, j int) bool { return rows[i].name < rows[j].name })
	var b strings.Builder
	fmt.Fprintf(
		&b,
		"// Code generated by gen from %s; DO NOT EDIT.\n\npackage emojinames\n\nvar names = [...]Entry{\n",
		*src,
	)
	for _, r := range rows {
		fmt.Fprintf(&b, "\t{%s, %s, %t},\n", strconv.Quote(r.name), strconv.QuoteToASCII(r.emoji), r.tones)
	}
	b.WriteString("}\n")
	//nolint:gosec // a source file git tracks, readable by all
	if err = os.WriteFile(*out, []byte(b.String()), 0o644); err != nil {
		log.Fatal(err)
	}
}

func read(src string) ([]byte, error) {
	if !strings.HasPrefix(src, "http") {
		return os.ReadFile(src)
	}
	resp, err := http.Get(src) //nolint:gosec,noctx // the table's source, the -src flag of a one-off generator
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("%s: %s", src, resp.Status)
	}
	return io.ReadAll(resp.Body)
}
