package main

import (
	"fmt"
	"io"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

// command is how the guide's pages say they were made.
const command = "`task test:chrome` (the Chrome pixel tests, then `go run ./ui/internal/parity -docs docs/05-ui`)"

var marker = regexp.MustCompile(`(?s)<!-- chrome( [^ >]+)? -->\n.*?<!-- /chrome -->`)

// fill writes every card's sentence between its markers in dir's kit
// pages, and the summary page listing them all, then every pixel page.
func fill(dir string, rs []result) error {
	cards := map[string]result{}
	for _, r := range rs {
		if r.Kind == "card" {
			cards[r.Name] = r
		}
	}
	pages, err := filepath.Glob(filepath.Join(dir, "07-kit", "*.md"))
	if err != nil {
		return err
	}
	var rows []row
	used := map[string]bool{}
	for _, page := range pages {
		placed, pageErr := fillPage(page, cards, used)
		if pageErr != nil {
			return pageErr
		}
		rows = append(rows, placed...)
	}
	var unplaced []string
	for name := range cards {
		if !used[name] {
			unplaced = append(unplaced, name)
		}
	}
	if len(unplaced) > 0 {
		sort.Strings(unplaced)
		return fmt.Errorf("cards with no <!-- chrome --> markers in %s: %s",
			filepath.Join(dir, "07-kit"), strings.Join(unplaced, ", "))
	}
	sort.Slice(rows, func(i, j int) bool { return rows[i].name < rows[j].name })
	return writeFile(filepath.Join(dir, "08-chrome.md"), func(w io.Writer) error {
		var b strings.Builder
		fmt.Fprintf(&b, "# Matches Chrome\n\nGenerated by %s from the pixel tests' report; don't edit.\n\n", command)
		b.WriteString("| Component | Mean difference | Threshold |\n|---|---|---|\n")
		for _, r := range rows {
			c := cards[r.name]
			fmt.Fprintf(&b, "| [%s](%s) | %s | %s |\n", r.title, r.link, percent(c.Mean), percent(c.Threshold))
		}
		var pages []result
		for _, r := range rs {
			if r.Kind == "page" {
				pages = append(pages, r)
			}
		}
		if len(pages) > 0 {
			sort.Slice(pages, func(i, j int) bool { return pages[i].Name < pages[j].Name })
			b.WriteString("\n## Pixel pages\n\nPages of the CSS subset itself (borders, gradients, clips, text, images…), " +
				"each drawn by ember and by Chrome.\n\n")
			b.WriteString("| Page | Mean difference | Threshold |\n|---|---|---|\n")
			for _, p := range pages {
				fmt.Fprintf(&b, "| %s | %s | %s |\n", p.Name, percent(p.Mean), percent(p.Threshold))
			}
		}
		_, werr := io.WriteString(w, b.String())
		return werr
	})
}

// row is a card's line in the summary page.
type row struct{ name, title, link string }

// fillPage writes the sentence of each card marked in page, recording it in
// used, and returns the rows of the cards it placed.
func fillPage(page string, cards map[string]result, used map[string]bool) ([]row, error) {
	data, err := os.ReadFile(page)
	if err != nil {
		return nil, err
	}
	own := strings.TrimSuffix(filepath.Base(page), ".md")
	title := heading(string(data))
	var rows []row
	var missing []string
	out := marker.ReplaceAllStringFunc(string(data), func(m string) string {
		name := own
		if sub := marker.FindStringSubmatch(m); sub[1] != "" {
			name = strings.TrimSpace(sub[1])
		}
		r, ok := cards[name]
		if !ok {
			missing = append(missing, name)
			return m
		}
		used[name] = true
		t := title
		if number(name) != number(own) {
			t = fmt.Sprintf("%s: %s", title, variant(name, own))
		}
		rows = append(rows, row{name, t, "07-kit/" + filepath.Base(page)})
		tag := "<!-- chrome -->"
		if sub := marker.FindStringSubmatch(m); sub[1] != "" {
			tag = "<!-- chrome " + name + " -->"
		}
		return fmt.Sprintf("%s\nMatches Chrome within %s of its pixels (threshold %s).\n<!-- /chrome -->",
			tag, percent(r.Mean), percent(r.Threshold))
	})
	if len(missing) > 0 {
		return nil, fmt.Errorf("%s: no card results for %s", page, strings.Join(missing, ", "))
	}
	if out != string(data) {
		// The guide's own kit pages, found by Glob in the folder given.
		if writeErr := os.WriteFile(page, []byte(out), 0o600); writeErr != nil { //nolint:gosec // see above
			return nil, writeErr
		}
	}
	return rows, nil
}

func heading(md string) string {
	for _, l := range strings.Split(md, "\n") {
		if strings.HasPrefix(l, "# ") {
			return strings.TrimSpace(l[2:])
		}
	}
	return ""
}

func percent(v float64) string { return fmt.Sprintf("%.2f%%", 100*v) }

// number is a page's or card's number, 14b in 14b-search.
func number(name string) string { return strings.SplitN(name, "-", 2)[0] }

// variant is what sets an extra card apart from its page: "save" for
// 32b-file-dialog-save on 32-file-dialog, "search" for 14b-search.
func variant(card, page string) string {
	rest := func(n string) string {
		if _, r, ok := strings.Cut(n, "-"); ok {
			return r
		}
		return n
	}
	v := strings.TrimPrefix(rest(card), rest(page)+"-")
	return strings.ReplaceAll(v, "-", " ")
}
